"""embed: chunks of a package -> vectors in pgvector. Full-text search needs no processor:
the chunk table's tsvector column is generated by Postgres."""

from lake_core.embedding import Embedder, to_pgvector
from sqlalchemy import text

from lake_processors.contract import Context

BATCH = 64


class EmbedProcessor:
    name = "embed"
    cost = "cpu"

    def __init__(self, embedder: Embedder) -> None:
        self.embedder = embedder
        self.version = embedder.model  # a new model = new job rows = re-embed everything

    def run(self, target: str, ctx: Context) -> None:
        with ctx.engine.begin() as c:
            rows = c.execute(
                text(
                    "select id, text from chunk where package_id=:p and not exists "
                    "(select 1 from embedding e where e.chunk_id=chunk.id and e.model=:m) "
                    "order by ordinal"
                ),
                {"p": target, "m": self.embedder.model},
            ).all()
            for i in range(0, len(rows), BATCH):
                part = rows[i : i + BATCH]
                vecs = self.embedder.embed([r.text for r in part])
                for r, v in zip(part, vecs, strict=True):
                    c.execute(
                        text(
                            "insert into embedding(chunk_id,model,vec) "
                            "values (:c,:m,cast(:v as vector)) on conflict do nothing"
                        ),
                        {"c": r.id, "m": self.embedder.model, "v": to_pgvector(v)},
                    )
